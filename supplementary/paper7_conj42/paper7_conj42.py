# 5. Peres-Mermin square: direct Z/2 class verification
# =========================================================

def peres_mermin_square():
    """
    The Mermin magic square (2-qubit observables):

        XI   IX   XX
        IZ   ZI   ZZ
        XZ   ZX   YY

    Row products = I (each row commutes, product = +I).
    Column products: col1=I, col2=I, col3=-I.

    The discrepancy -I is the non-trivial Z/2 class [f] in Paper III.
    This is the correct object for Conjecture 4.1: [f] != 0 in H^2(G_PM, Z/2).
    """
    I = np.eye(2, dtype=complex)
    X = np.array([[0,1],[1,0]], dtype=complex)
    Y = np.array([[0,-1j],[1j,0]], dtype=complex)
    Z = np.array([[1,0],[0,-1]], dtype=complex)

    def kron(A, B):
        return np.kron(A, B)

    square = [
        [kron(X, I), kron(I, X), kron(X, X)],  # row 1
        [kron(I, Z), kron(Z, I), kron(Z, Z)],  # row 2
        [kron(X, Z), kron(Z, X), kron(Y, Y)],  # row 3
    ]

    print("\n  Peres-Mermin magic square (2-qubit):")
    labels = [['XI','IX','XX'], ['IZ','ZI','ZZ'], ['XZ','ZX','YY']]

    # Verify rows and columns all commute within each context
    for r in range(3):
        for i in range(3):
            for j in range(i+1, 3):
                AB = square[r][i] @ square[r][j]
                BA = square[r][j] @ square[r][i]
                assert np.allclose(AB, BA), f"Row {r}: {labels[r][i]},{labels[r][j]} don't commute"
    for c in range(3):
        for i in range(3):
            for j in range(i+1, 3):
                AB = square[i][c] @ square[j][c]
                BA = square[j][c] @ square[i][c]
                assert np.allclose(AB, BA), f"Col {c}: {labels[i][c]},{labels[j][c]} don't commute"
    print("    All within-context pairs commute ✓")

    # Compute row and column products
    print("    Row products:")
    for r in range(3):
        prod = square[r][0] @ square[r][1] @ square[r][2]
        diag = prod[0,0]
        name = "+I" if np.isclose(diag, 1.0) else "-I" if np.isclose(diag, -1.0) else f"{diag}·I"
        print(f"      {' · '.join(labels[r])} = {name}")
        assert np.allclose(prod, np.eye(4)), f"Row {r} product != I"

    print("    Column products:")
    col_signs = []
    for c in range(3):
        prod = square[0][c] @ square[1][c] @ square[2][c]
        diag = np.round(prod[0,0], 10)
        name = "+I" if np.isclose(diag, 1.0) else "-I" if np.isclose(diag, -1.0) else f"{diag}·I"
        print(f"      {labels[0][c]} · {labels[1][c]} · {labels[2][c]} = {name}")
        assert np.allclose(prod, diag * np.eye(4)), f"Col {c} product is not scalar"
        col_signs.append(diag)

    # The global product: all rows = +I, all cols = col1*col2*col3
    global_sign = col_signs[0] * col_signs[1] * col_signs[2]
    print(f"    Global product via columns: {np.round(global_sign, 10)}·I")
    print(f"    Global product via rows:    +I")

    class_nontrivial = not np.isclose(global_sign, 1.0)
    if class_nontrivial:
        print(f"    Contradiction: row-product = +I ≠ col-product = {np.round(global_sign,10)}·I")
        print(f"    → [f] = -1 (generator of Z/2)  ← non-trivial Z/2 class  ✓")
    else:
        print("    No contradiction found — [f] = 0  ✗")
    return class_nontrivial


